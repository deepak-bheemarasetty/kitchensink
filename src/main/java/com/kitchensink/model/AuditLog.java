package com.kitchensink.model;

import java.time.Instant;
import java.util.Map;
import java.util.Set;
import org.bson.types.ObjectId;
import org.springframework.data.annotation.Id;

/** Immutable history record for security and member changes. */
@org.springframework.data.mongodb.core.mapping.Document(collection = "audit_logs")
public class AuditLog {
  private static final Set<String> ACTIONS = Set.of(
      "member.create", "member.update", "member.delete", "member.restore",
      "user.roleChange", "role.update", "auth.loginFailed");
  @Id private ObjectId id;
  private Instant at;
  private ObjectId actorId;
  private String action;
  private String entityType;
  private ObjectId entityId;
  private Map<String, Object> changes;
  private String requestId;
  private String ip;

  public ObjectId getId() { return id; }
  public void setId(ObjectId id) { this.id = id; }
  public Instant getAt() { return at; }
  public void setAt(Instant at) { this.at = at; }
  public ObjectId getActorId() { return actorId; }
  public void setActorId(ObjectId actorId) { this.actorId = actorId; }
  public String getAction() { return action; }
  public void setAction(String action) { this.action = action; }
  public String getEntityType() { return entityType; }
  public void setEntityType(String entityType) { this.entityType = entityType; }
  public ObjectId getEntityId() { return entityId; }
  public void setEntityId(ObjectId entityId) { this.entityId = entityId; }
  public Map<String, Object> getChanges() { return changes; }
  public void setChanges(Map<String, Object> changes) {
    this.changes = changes == null ? null : Map.copyOf(changes);
  }
  public String getRequestId() { return requestId; }
  public void setRequestId(String requestId) { this.requestId = requestId; }
  public String getIp() { return ip; }
  public void setIp(String ip) { this.ip = ip; }

  /** Validates an audit record before its insert-only persistence operation. */
  public void validateForInsert() {
    if (id != null) throw new IllegalStateException("Audit IDs are generated by MongoDB");
    if (at == null || actorId == null || entityId == null) throw new IllegalStateException("Audit identity and timestamp are required");
    if (action == null || !ACTIONS.contains(action)) throw new IllegalStateException("Audit action is invalid");
    if (entityType == null || entityType.isBlank() || entityType.length() > 40) throw new IllegalStateException("Audit entity type is invalid");
    if (requestId == null || requestId.isBlank() || requestId.length() > 128) throw new IllegalStateException("Audit request ID is invalid");
    if (changes == null) throw new IllegalStateException("Audit changes are required");
    if (changes.keySet().stream().anyMatch(key -> key.toLowerCase().contains("password") || key.startsWith("$") || key.contains("."))) {
      throw new IllegalStateException("Audit changes cannot contain secrets or MongoDB operators");
    }
    if (ip != null && ip.length() > 64) throw new IllegalStateException("Audit IP is too long");
  }
}
